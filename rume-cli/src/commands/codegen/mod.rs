use std::fs;
use std::path::Path;

pub fn run(dry_run: bool) {
    if !Path::new("Cargo.toml").is_file() {
        eprintln!("error: not a Rust project (Cargo.toml not found)");
        std::process::exit(1);
    }

    let handlers_dir = Path::new("src/handlers");
    if !handlers_dir.is_dir() {
        eprintln!("error: src/handlers directory not found");
        std::process::exit(1);
    }

    regenerate_dir(handlers_dir, "handler", dry_run);
    regenerate_dir(Path::new("src/models"), "model", dry_run);
    regenerate_dir(Path::new("src/services"), "service", dry_run);
    regenerate_dir(Path::new("src/middleware"), "middleware", dry_run);

    // Validate routes.rs marker.
    let routes_path = Path::new("src/routes.rs");
    if routes_path.is_file() {
        match fs::read_to_string(routes_path) {
            Ok(content) if content.contains("// rume:routes") => {
                println!("  routes.rs marker present");
            }
            Ok(_) => {
                println!("  warning: src/routes.rs is missing the `// rume:routes` marker");
            }
            Err(err) => {
                eprintln!("  warning: could not read src/routes.rs: {err}");
            }
        }
    }
}

fn is_valid_rust_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' => {
            chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
        }
        _ => false,
    }
}

fn regenerate_dir(dir: &Path, label: &str, dry_run: bool) {
    if !dir.is_dir() {
        return;
    }

    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(err) => {
            eprintln!("error: failed to read {}: {err}", dir.display());
            return;
        }
    };

    let mut modules: Vec<String> = Vec::new();
    for entry in entries.flatten() {
        let path = entry.path();
        if path.extension().and_then(|ext| ext.to_str()) != Some("rs") {
            continue;
        }
        let Some(stem) = path.file_stem().and_then(|stem| stem.to_str()) else {
            continue;
        };
        if stem == "mod" || !is_valid_rust_identifier(stem) {
            continue;
        }
        modules.push(stem.to_string());
    }

    modules.sort();

    let mut content = String::from("// Generated by `rume codegen`. Do not edit by hand.\n");
    for module in &modules {
        content.push_str(&format!("pub mod {module};\n"));
    }

    let mod_path = dir.join("mod.rs");
    if dry_run {
        println!("Would regenerate {} (dry-run):", mod_path.display());
        println!("  {} {} module(s)", modules.len(), label);
        return;
    }

    if let Err(err) = fs::write(&mod_path, content) {
        eprintln!("error: failed to write {}: {err}", mod_path.display());
        std::process::exit(1);
    }

    println!("Regenerated {}", mod_path.display());
    println!("  {} {} module(s)", modules.len(), label);
}
