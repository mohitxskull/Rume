//! Pure-Rust OpenAPI v3.1 to TypeScript interfaces and `fetch` client generator.

use std::collections::{BTreeSet, HashSet};
use std::fmt::Write;

use serde_json::{Map, Value};

const HTTP_METHODS: &[&str] = &["get", "post", "put", "patch", "delete", "head", "options"];

/// Generate TypeScript interfaces and a typed `fetch` client (`RumeApiClient` + `createClient`)
/// from an OpenAPI v3.1 JSON document.
pub fn generate_typescript(spec: &Value) -> String {
    let mut out = String::new();
    out.push_str("// Generated by `rume openapi ts`. Do not edit manually.\n\n");

    emit_component_schemas(spec, &mut out);
    emit_client(spec, &mut out);

    out
}

fn emit_component_schemas(spec: &Value, out: &mut String) {
    let Some(schemas) = spec
        .get("components")
        .and_then(|c| c.get("schemas"))
        .and_then(Value::as_object)
    else {
        return;
    };

    for (name, schema) in schemas {
        let ts_name = sanitize_pascal_ident(name);
        if is_object_schema(schema) {
            let _ = writeln!(out, "export interface {ts_name} {{");
            emit_object_fields(schema, out, "  ");
            out.push_str("}\n\n");
        } else {
            let ts_type = schema_to_ts(schema);
            let _ = writeln!(out, "export type {ts_name} = {ts_type};\n");
        }
    }
}

fn is_object_schema(schema: &Value) -> bool {
    schema
        .get("properties")
        .and_then(Value::as_object)
        .is_some()
        || schema.get("type").and_then(Value::as_str) == Some("object")
}

fn emit_object_fields(schema: &Value, out: &mut String, indent: &str) {
    let required: HashSet<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|arr| arr.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();

    let Some(props) = schema.get("properties").and_then(Value::as_object) else {
        return;
    };

    for (prop_name, prop_schema) in props {
        let opt = if required.contains(prop_name.as_str()) {
            ""
        } else {
            "?"
        };
        let key = format_prop_key(prop_name);
        let ts_type = schema_to_ts(prop_schema);
        let _ = writeln!(out, "{indent}{key}{opt}: {ts_type};");
    }
}

fn schema_to_ts(schema: &Value) -> String {
    if let Some(ref_str) = schema.get("$ref").and_then(Value::as_str) {
        let raw_name = ref_str.rsplit('/').next().unwrap_or(ref_str);
        return sanitize_pascal_ident(raw_name);
    }

    if let Some(enum_vals) = schema.get("enum").and_then(Value::as_array)
        && !enum_vals.is_empty()
    {
        let variants: Vec<String> = enum_vals
            .iter()
            .map(|v| match v {
                Value::String(s) => format!("{s:?}"),
                Value::Number(n) => n.to_string(),
                Value::Bool(b) => b.to_string(),
                Value::Null => "null".to_string(),
                _ => "unknown".to_string(),
            })
            .collect();
        return variants.join(" | ");
    }

    for key in ["oneOf", "anyOf"] {
        if let Some(variants) = schema.get(key).and_then(Value::as_array)
            && !variants.is_empty()
        {
            return variants
                .iter()
                .map(schema_to_ts)
                .collect::<Vec<_>>()
                .join(" | ");
        }
    }

    if let Some(variants) = schema.get("allOf").and_then(Value::as_array)
        && !variants.is_empty()
    {
        return variants
            .iter()
            .map(schema_to_ts)
            .collect::<Vec<_>>()
            .join(" & ");
    }

    match schema.get("type") {
        Some(Value::String(ty)) => single_type_to_ts(ty, schema),
        Some(Value::Array(types)) => {
            let parts: Vec<String> = types
                .iter()
                .filter_map(Value::as_str)
                .map(|t| single_type_to_ts(t, schema))
                .collect();
            if parts.is_empty() {
                "unknown".to_string()
            } else {
                parts.join(" | ")
            }
        }
        _ => {
            if schema
                .get("properties")
                .and_then(Value::as_object)
                .is_some()
            {
                inline_object_ts(schema)
            } else {
                "unknown".to_string()
            }
        }
    }
}

fn single_type_to_ts(ty: &str, schema: &Value) -> String {
    match ty {
        "string" => "string".to_string(),
        "integer" | "number" => "number".to_string(),
        "boolean" => "boolean".to_string(),
        "null" => "null".to_string(),
        "array" => {
            let item_ts = schema
                .get("items")
                .map(schema_to_ts)
                .unwrap_or_else(|| "unknown".to_string());
            format!("Array<{item_ts}>")
        }
        "object" => inline_object_ts(schema),
        _ => "unknown".to_string(),
    }
}

fn inline_object_ts(schema: &Value) -> String {
    if let Some(props) = schema.get("properties").and_then(Value::as_object)
        && !props.is_empty()
    {
        let required: HashSet<&str> = schema
            .get("required")
            .and_then(Value::as_array)
            .map(|arr| arr.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();

        let fields: Vec<String> = props
            .iter()
            .map(|(k, v)| {
                let opt = if required.contains(k.as_str()) {
                    ""
                } else {
                    "?"
                };
                format!("{}{}: {};", format_prop_key(k), opt, schema_to_ts(v))
            })
            .collect();
        return format!("{{ {} }}", fields.join(" "));
    }

    if let Some(additional) = schema.get("additionalProperties")
        && additional.is_object()
    {
        return format!("Record<string, {}>", schema_to_ts(additional));
    }

    "Record<string, unknown>".to_string()
}

struct ParamSpec {
    name: String,
    ts_name: String,
    required: bool,
    ts_type: String,
}

fn emit_client(spec: &Value, out: &mut String) {
    out.push_str(
        "export type FetchLike = (input: RequestInfo | URL, init?: RequestInit) => Promise<Response>;\n\n",
    );
    out.push_str("export class RumeApiClient {\n");
    out.push_str("  private readonly baseUrl: string;\n");
    out.push_str("  private readonly fetchImpl: FetchLike;\n\n");
    out.push_str(
        "  constructor(baseUrl: string, fetchImpl: FetchLike = globalThis.fetch.bind(globalThis)) {\n",
    );
    out.push_str("    this.baseUrl = baseUrl.replace(/\\/+$/, \"\");\n");
    out.push_str("    this.fetchImpl = fetchImpl;\n");
    out.push_str("  }\n");

    let mut used_names = HashSet::new();
    if let Some(paths) = spec.get("paths").and_then(Value::as_object) {
        for (path, path_item) in paths {
            let Some(path_obj) = path_item.as_object() else {
                continue;
            };
            for &method in HTTP_METHODS {
                let Some(op) = path_obj.get(method).and_then(Value::as_object) else {
                    continue;
                };
                emit_operation_method(path, method, op, &mut used_names, out);
            }
        }
    }

    out.push_str("}\n\n");
    out.push_str(
        "export function createClient(baseUrl: string, fetchImpl?: FetchLike): RumeApiClient {\n",
    );
    out.push_str("  return new RumeApiClient(baseUrl, fetchImpl);\n");
    out.push_str("}\n");
}

fn emit_operation_method(
    path: &str,
    method: &str,
    op: &Map<String, Value>,
    used_names: &mut HashSet<String>,
    out: &mut String,
) {
    let raw_name = op
        .get("operationId")
        .and_then(Value::as_str)
        .filter(|s| !s.trim().is_empty())
        .map(sanitize_camel_ident)
        .unwrap_or_else(|| sanitize_camel_ident(&format!("{method}_{path}")));

    let method_name = deduplicate_name(raw_name, used_names);
    let (path_params, query_params) = collect_parameters(path, op);
    let request_body = extract_request_body(op);
    let return_type = extract_response_type(op);

    let mut required_params = Vec::new();
    let mut optional_params = Vec::new();
    for p in &path_params {
        required_params.push(format!("{}: {}", p.ts_name, p.ts_type));
    }

    if !query_params.is_empty() {
        let any_required = query_params.iter().any(|q| q.required);
        let q_opt = if any_required { "" } else { "?" };
        let q_fields: Vec<String> = query_params
            .iter()
            .map(|q| {
                let opt = if q.required { "" } else { "?" };
                format!("{}{}: {};", format_prop_key(&q.name), opt, q.ts_type)
            })
            .collect();
        let param = format!("query{q_opt}: {{ {} }}", q_fields.join(" "));
        if any_required {
            required_params.push(param);
        } else {
            optional_params.push(param);
        }
    }

    if let Some((required, body_ts)) = &request_body {
        let opt = if *required { "" } else { "?" };
        let param = format!("body{opt}: {body_ts}");
        if *required {
            required_params.push(param);
        } else {
            optional_params.push(param);
        }
    }

    // Why: TypeScript rejects a required parameter after an optional parameter (TS1016),
    // so emit all required parameters (path, required query, required body) before optional ones.
    let mut sig_params = required_params;
    sig_params.extend(optional_params);

    let _ = writeln!(
        out,
        "\n  async {method_name}({}): Promise<{return_type}> {{",
        sig_params.join(", ")
    );

    let url_expr = build_url_template(path, &path_params);
    if query_params.is_empty() {
        let _ = writeln!(out, "    const url = `{url_expr}`;");
    } else {
        let _ = writeln!(out, "    const searchParams = new URLSearchParams();");
        for q in &query_params {
            let prop_access = if is_valid_js_ident(&q.name) {
                format!("query?.{}", q.name)
            } else {
                format!("query?.[{:?}]", q.name)
            };
            let _ = writeln!(
                out,
                "    if ({prop_access} !== undefined) searchParams.set({:?}, String({prop_access}));",
                q.name
            );
        }
        let _ = writeln!(out, "    const qs = searchParams.toString();");
        let _ = writeln!(
            out,
            "    const url = qs ? `{url_expr}?${{qs}}` : `{url_expr}`;"
        );
    }

    let upper_method = method.to_ascii_uppercase();
    if request_body.is_some() {
        let _ = writeln!(out, "    const res = await this.fetchImpl(url, {{");
        let _ = writeln!(out, "      method: {upper_method:?},");
        let _ = writeln!(
            out,
            "      headers: body !== undefined ? {{ \"Content-Type\": \"application/json\" }} : undefined,"
        );
        let _ = writeln!(
            out,
            "      body: body !== undefined ? JSON.stringify(body) : undefined,"
        );
        let _ = writeln!(out, "    }});");
    } else {
        let _ = writeln!(
            out,
            "    const res = await this.fetchImpl(url, {{ method: {upper_method:?} }});"
        );
    }

    out.push_str(
        "    if (!res.ok) {\n      throw new Error(`HTTP ${res.status}: ${await res.text()}`);\n    }\n",
    );
    if return_type == "void" {
        out.push_str("    return;\n");
    } else {
        let _ = writeln!(out, "    return (await res.json()) as {return_type};");
    }
    out.push_str("  }");
}

fn collect_parameters(path: &str, op: &Map<String, Value>) -> (Vec<ParamSpec>, Vec<ParamSpec>) {
    let mut path_params = Vec::new();
    let mut query_params = Vec::new();
    let mut seen_path = BTreeSet::new();

    if let Some(params) = op.get("parameters").and_then(Value::as_array) {
        for p in params {
            let Some(name) = p.get("name").and_then(Value::as_str) else {
                continue;
            };
            let location = p.get("in").and_then(Value::as_str).unwrap_or("");
            let required = p.get("required").and_then(Value::as_bool).unwrap_or(false);
            let ts_type = p
                .get("schema")
                .map(schema_to_ts)
                .unwrap_or_else(|| "string".to_string());

            match location {
                "path" => {
                    seen_path.insert(name.to_string());
                    path_params.push(ParamSpec {
                        name: name.to_string(),
                        ts_name: sanitize_param_ident(name),
                        required: true,
                        ts_type,
                    });
                }
                "query" => {
                    query_params.push(ParamSpec {
                        name: name.to_string(),
                        ts_name: sanitize_param_ident(name),
                        required,
                        ts_type,
                    });
                }
                _ => {}
            }
        }
    }

    // Ensure any `{param}` in the path template is present even if `parameters` omitted it.
    for seg in path.split('/') {
        if let Some(raw) = seg.strip_prefix('{').and_then(|s| s.strip_suffix('}')) {
            let name = raw.strip_prefix('*').unwrap_or(raw);
            if !name.is_empty() && !seen_path.contains(name) {
                seen_path.insert(name.to_string());
                path_params.push(ParamSpec {
                    name: name.to_string(),
                    ts_name: sanitize_param_ident(name),
                    required: true,
                    ts_type: "string".to_string(),
                });
            }
        }
    }

    (path_params, query_params)
}

fn extract_request_body(op: &Map<String, Value>) -> Option<(bool, String)> {
    let body = op.get("requestBody")?;
    let required = body
        .get("required")
        .and_then(Value::as_bool)
        .unwrap_or(false);
    let schema = body
        .get("content")
        .and_then(|c| c.get("application/json"))
        .and_then(|j| j.get("schema"))?;
    Some((required, schema_to_ts(schema)))
}

fn extract_response_type(op: &Map<String, Value>) -> String {
    let Some(responses) = op.get("responses").and_then(Value::as_object) else {
        return "void".to_string();
    };

    for status in ["200", "201", "202", "204"] {
        if let Some(resp) = responses.get(status) {
            return response_schema_or_void(status, resp);
        }
    }

    if let Some((status, resp)) = responses.iter().find(|(k, _)| k.starts_with('2')) {
        return response_schema_or_void(status, resp);
    }

    "void".to_string()
}

fn response_schema_or_void(status: &str, resp: &Value) -> String {
    if status == "204" {
        return "void".to_string();
    }
    resp.get("content")
        .and_then(|c| c.get("application/json"))
        .and_then(|j| j.get("schema"))
        .map(schema_to_ts)
        .unwrap_or_else(|| "void".to_string())
}

fn build_url_template(path: &str, path_params: &[ParamSpec]) -> String {
    let mut rendered = String::from("${this.baseUrl}");
    if !path.starts_with('/') {
        rendered.push('/');
    }
    for (idx, seg) in path.split('/').enumerate() {
        if idx > 0 {
            rendered.push('/');
        }
        if let Some(raw) = seg.strip_prefix('{').and_then(|s| s.strip_suffix('}')) {
            let name = raw.strip_prefix('*').unwrap_or(raw);
            let ts_name = path_params
                .iter()
                .find(|p| p.name == name)
                .map(|p| p.ts_name.as_str())
                .unwrap_or(name);
            let _ = write!(rendered, "${{encodeURIComponent(String({ts_name}))}}");
        } else {
            rendered.push_str(&escape_ts_template_literal(seg));
        }
    }
    rendered
}

/// Escape characters that have special meaning inside a JavaScript/TypeScript template literal.
fn escape_ts_template_literal(segment: &str) -> String {
    let mut out = String::with_capacity(segment.len());
    let mut chars = segment.chars().peekable();
    while let Some(ch) = chars.next() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '`' => out.push_str("\\`"),
            '$' if chars.peek() == Some(&'{') => out.push_str("\\$"),
            _ => out.push(ch),
        }
    }
    out
}

fn sanitize_camel_ident(raw: &str) -> String {
    let tokens: Vec<&str> = raw
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|t| !t.is_empty())
        .collect();

    if tokens.is_empty() {
        return "request".to_string();
    }

    let mut out = String::new();
    for (idx, token) in tokens.iter().enumerate() {
        if idx == 0 {
            let mut chars = token.chars();
            if let Some(first) = chars.next() {
                if first.is_ascii_digit() {
                    out.push('_');
                }
                out.push(first.to_ascii_lowercase());
                out.push_str(chars.as_str());
            }
        } else {
            let mut chars = token.chars();
            if let Some(first) = chars.next() {
                out.push(first.to_ascii_uppercase());
                out.push_str(chars.as_str());
            }
        }
    }
    out
}

fn sanitize_pascal_ident(raw: &str) -> String {
    let tokens: Vec<&str> = raw
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|t| !t.is_empty())
        .collect();

    if tokens.is_empty() {
        return "Schema".to_string();
    }

    let mut out = String::new();
    for token in tokens {
        let mut chars = token.chars();
        if let Some(first) = chars.next() {
            if out.is_empty() && first.is_ascii_digit() {
                out.push('_');
            }
            out.push(first.to_ascii_uppercase());
            out.push_str(chars.as_str());
        }
    }
    out
}

fn sanitize_param_ident(raw: &str) -> String {
    if is_valid_js_ident(raw) {
        return raw.to_string();
    }
    let cleaned: String = raw
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' || c == '$' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if cleaned.is_empty() || cleaned.starts_with(|c: char| c.is_ascii_digit()) {
        format!("_{cleaned}")
    } else {
        cleaned
    }
}

fn is_valid_js_ident(s: &str) -> bool {
    let mut chars = s.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !(first.is_ascii_alphabetic() || first == '_' || first == '$') {
        return false;
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

fn format_prop_key(name: &str) -> String {
    if is_valid_js_ident(name) {
        name.to_string()
    } else {
        format!("{name:?}")
    }
}

fn deduplicate_name(base: String, used: &mut HashSet<String>) -> String {
    if used.insert(base.clone()) {
        return base;
    }
    let mut suffix = 2usize;
    loop {
        let candidate = format!("{base}_{suffix}");
        if used.insert(candidate.clone()) {
            return candidate;
        }
        suffix += 1;
    }
}

