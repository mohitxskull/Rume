//! Pure-Rust OpenAPI v3.1 to TypeScript interfaces and `fetch` client generator.

use std::collections::{BTreeSet, HashMap, HashSet};
use std::fmt::Write;

use serde_json::{Map, Value};

const HTTP_METHODS: &[&str] = &["get", "post", "put", "patch", "delete", "head", "options"];

/// Generate TypeScript interfaces and a typed `fetch` client (`RumeApiClient` + `createClient`)
/// from an OpenAPI v3.1 JSON document.
pub fn generate_typescript(spec: &Value) -> String {
    let mut out = String::new();
    out.push_str("// Generated by `rume openapi ts`. Do not edit manually.\n\n");

    let schema_name_map = build_schema_name_map(spec);
    emit_component_schemas(spec, &schema_name_map, &mut out);
    emit_client(spec, &schema_name_map, &mut out);

    out
}

/// Precomputes the deterministic mapping from raw OpenAPI schema name -> deduplicated
/// TypeScript identifier so `$ref` resolution targets the exact emitted interface/type
/// even when two raw schema names sanitize to the same PascalCase identifier (`P2-21`).
fn build_schema_name_map(spec: &Value) -> HashMap<&str, String> {
    let mut map = HashMap::new();
    let Some(schemas) = spec
        .get("components")
        .and_then(|c| c.get("schemas"))
        .and_then(Value::as_object)
    else {
        return map;
    };
    let mut used = HashSet::new();
    for name in schemas.keys() {
        let ts_name = deduplicate_name(sanitize_pascal_ident(name), &mut used);
        map.insert(name.as_str(), ts_name);
    }
    map
}

fn emit_component_schemas(spec: &Value, schema_names: &HashMap<&str, String>, out: &mut String) {
    let Some(schemas) = spec
        .get("components")
        .and_then(|c| c.get("schemas"))
        .and_then(Value::as_object)
    else {
        return;
    };

    for (name, schema) in schemas {
        let ts_name = schema_names
            .get(name.as_str())
            .cloned()
            .unwrap_or_else(|| sanitize_pascal_ident(name));
        if is_object_schema(schema) {
            let _ = writeln!(out, "export interface {ts_name} {{");
            emit_object_fields(schema, schema_names, out, "  ");
            out.push_str("}\n\n");
        } else {
            let ts_type = schema_to_ts(schema, schema_names);
            let _ = writeln!(out, "export type {ts_name} = {ts_type};\n");
        }
    }
}

fn is_object_schema(schema: &Value) -> bool {
    // Why: require non-empty `properties` before emitting an `interface`, so
    // `type: "object"` + `additionalProperties` schemas fall through to `schema_to_ts`
    // and emit `export type Foo = Record<string, ...>;` instead of empty `interface Foo {}` (`RC-20`).
    schema
        .get("properties")
        .and_then(Value::as_object)
        .is_some_and(|props| !props.is_empty())
}

fn emit_object_fields(
    schema: &Value,
    schema_names: &HashMap<&str, String>,
    out: &mut String,
    indent: &str,
) {
    let required: HashSet<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|arr| arr.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();

    let Some(props) = schema.get("properties").and_then(Value::as_object) else {
        return;
    };

    for (prop_name, prop_schema) in props {
        let opt = if required.contains(prop_name.as_str()) {
            ""
        } else {
            "?"
        };
        let key = format_prop_key(prop_name);
        let ts_type = schema_to_ts(prop_schema, schema_names);
        let _ = writeln!(out, "{indent}{key}{opt}: {ts_type};");
    }
}

fn schema_to_ts(schema: &Value, schema_names: &HashMap<&str, String>) -> String {
    if let Some(ref_str) = schema.get("$ref").and_then(Value::as_str) {
        let raw_name = ref_str.rsplit('/').next().unwrap_or(ref_str);
        return schema_names
            .get(raw_name)
            .cloned()
            .unwrap_or_else(|| sanitize_pascal_ident(raw_name));
    }

    if let Some(enum_vals) = schema.get("enum").and_then(Value::as_array)
        && !enum_vals.is_empty()
    {
        let variants: Vec<String> = enum_vals
            .iter()
            .map(|v| match v {
                Value::String(s) => js_string_literal(s),
                Value::Number(n) => n.to_string(),
                Value::Bool(b) => b.to_string(),
                Value::Null => "null".to_string(),
                _ => "unknown".to_string(),
            })
            .collect();
        return variants.join(" | ");
    }

    for key in ["oneOf", "anyOf"] {
        if let Some(variants) = schema.get(key).and_then(Value::as_array)
            && !variants.is_empty()
        {
            return variants
                .iter()
                .map(|v| schema_to_ts(v, schema_names))
                .collect::<Vec<_>>()
                .join(" | ");
        }
    }

    if let Some(variants) = schema.get("allOf").and_then(Value::as_array)
        && !variants.is_empty()
    {
        return variants
            .iter()
            .map(|v| {
                let ts = schema_to_ts(v, schema_names);
                // Why: in TypeScript `&` binds tighter than `|`, so an unparenthesized
                // union inside an intersection (`A | B & C`) parses as `A | (B & C)` instead
                // of `(A | B) & C` (`RC-39`).
                if ts.contains(" | ") && !(ts.starts_with('(') && ts.ends_with(')')) {
                    format!("({ts})")
                } else {
                    ts
                }
            })
            .collect::<Vec<_>>()
            .join(" & ");
    }

    match schema.get("type") {
        Some(Value::String(ty)) => single_type_to_ts(ty, schema, schema_names),
        Some(Value::Array(types)) => {
            let parts: Vec<String> = types
                .iter()
                .filter_map(Value::as_str)
                .map(|t| single_type_to_ts(t, schema, schema_names))
                .collect();
            if parts.is_empty() {
                "unknown".to_string()
            } else {
                parts.join(" | ")
            }
        }
        _ => {
            if schema
                .get("properties")
                .and_then(Value::as_object)
                .is_some()
            {
                inline_object_ts(schema, schema_names)
            } else {
                "unknown".to_string()
            }
        }
    }
}

fn single_type_to_ts(ty: &str, schema: &Value, schema_names: &HashMap<&str, String>) -> String {
    match ty {
        "string" => "string".to_string(),
        "integer" | "number" => "number".to_string(),
        "boolean" => "boolean".to_string(),
        "null" => "null".to_string(),
        "array" => {
            let item_ts = schema
                .get("items")
                .map(|s| schema_to_ts(s, schema_names))
                .unwrap_or_else(|| "unknown".to_string());
            format!("Array<{item_ts}>")
        }
        "object" => inline_object_ts(schema, schema_names),
        _ => "unknown".to_string(),
    }
}

fn inline_object_ts(schema: &Value, schema_names: &HashMap<&str, String>) -> String {
    if let Some(props) = schema.get("properties").and_then(Value::as_object)
        && !props.is_empty()
    {
        let required: HashSet<&str> = schema
            .get("required")
            .and_then(Value::as_array)
            .map(|arr| arr.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();

        let fields: Vec<String> = props
            .iter()
            .map(|(k, v)| {
                let opt = if required.contains(k.as_str()) {
                    ""
                } else {
                    "?"
                };
                format!(
                    "{}{}: {};",
                    format_prop_key(k),
                    opt,
                    schema_to_ts(v, schema_names)
                )
            })
            .collect();
        return format!("{{ {} }}", fields.join(" "));
    }

    if let Some(additional) = schema.get("additionalProperties")
        && additional.is_object()
    {
        return format!("Record<string, {}>", schema_to_ts(additional, schema_names));
    }

    "Record<string, unknown>".to_string()
}

struct ParamSpec {
    name: String,
    ts_name: String,
    required: bool,
    ts_type: String,
}

fn emit_client(spec: &Value, schema_names: &HashMap<&str, String>, out: &mut String) {
    out.push_str(
        "export type FetchLike = (input: RequestInfo | URL, init?: RequestInit) => Promise<Response>;\n\n",
    );
    out.push_str("export class RumeApiClient {\n");
    out.push_str("  private readonly baseUrl: string;\n");
    out.push_str("  private readonly fetchImpl: FetchLike;\n\n");
    out.push_str(
        "  constructor(baseUrl: string, fetchImpl: FetchLike = globalThis.fetch.bind(globalThis)) {\n",
    );
    out.push_str("    this.baseUrl = baseUrl.replace(/\\/+$/, \"\");\n");
    out.push_str("    this.fetchImpl = fetchImpl;\n");
    out.push_str("  }\n");

    let mut used_names = HashSet::new();
    // Why: reserve `constructor` so an operation named `constructor` never emits
    // `async constructor(...)` which fails TypeScript compilation (`TS1089`, `RC-39`).
    used_names.insert("constructor".to_string());
    if let Some(paths) = spec.get("paths").and_then(Value::as_object) {
        for (path, path_item) in paths {
            let Some(path_obj) = path_item.as_object() else {
                continue;
            };
            let path_item_params = path_obj
                .get("parameters")
                .and_then(Value::as_array)
                .map(Vec::as_slice);
            for &method in HTTP_METHODS {
                let Some(op) = path_obj.get(method).and_then(Value::as_object) else {
                    continue;
                };
                emit_operation_method(
                    path,
                    method,
                    path_item_params,
                    op,
                    schema_names,
                    &mut used_names,
                    out,
                );
            }
        }
    }

    out.push_str("}\n\n");
    out.push_str(
        "export function createClient(baseUrl: string, fetchImpl?: FetchLike): RumeApiClient {\n",
    );
    out.push_str("  return new RumeApiClient(baseUrl, fetchImpl);\n");
    out.push_str("}\n");
}

fn emit_operation_method(
    path: &str,
    method: &str,
    path_item_params: Option<&[Value]>,
    op: &Map<String, Value>,
    schema_names: &HashMap<&str, String>,
    used_names: &mut HashSet<String>,
    out: &mut String,
) {
    let raw_name = op
        .get("operationId")
        .and_then(Value::as_str)
        .filter(|s| !s.trim().is_empty())
        .map(sanitize_camel_ident)
        .unwrap_or_else(|| sanitize_camel_ident(&format!("{method}_{path}")));

    let method_name = deduplicate_name(raw_name, used_names);
    let (mut path_params, query_params) =
        collect_parameters(path, path_item_params, op, schema_names);
    let request_body = extract_request_body(op, schema_names);
    let return_type = extract_response_type(op, schema_names);

    // Why: deduplicate all emitted parameter identifiers (path params, `query` bag, `body`)
    // AND reserve body-local `const` names (`url`, `res`, `searchParams`, `qs`) so routes
    // such as `/search/{query}`, `/proxy/{url}`, or `/items/{res}` never emit duplicate
    // parameter names or shadow method-body `const` bindings (`TS2451`, `RC-20`, `RC-06`).
    let mut used_param_names: HashSet<String> = ["url", "res", "searchParams", "qs"]
        .into_iter()
        .map(str::to_string)
        .collect();
    let mut required_params = Vec::new();
    let mut optional_params = Vec::new();
    for p in &mut path_params {
        p.ts_name = deduplicate_name(p.ts_name.clone(), &mut used_param_names);
        required_params.push(format!("{}: {}", p.ts_name, p.ts_type));
    }

    let query_param_name = if !query_params.is_empty() {
        let name = deduplicate_name("query".to_string(), &mut used_param_names);
        let any_required = query_params.iter().any(|q| q.required);
        let q_opt = if any_required { "" } else { "?" };
        let q_fields: Vec<String> = query_params
            .iter()
            .map(|q| {
                let opt = if q.required { "" } else { "?" };
                format!("{}{}: {};", format_prop_key(&q.name), opt, q.ts_type)
            })
            .collect();
        let param = format!("{name}{q_opt}: {{ {} }}", q_fields.join(" "));
        if any_required {
            required_params.push(param);
        } else {
            optional_params.push(param);
        }
        Some(name)
    } else {
        None
    };

    let body_param_name = if let Some((required, body_ts)) = &request_body {
        let name = deduplicate_name("body".to_string(), &mut used_param_names);
        let opt = if *required { "" } else { "?" };
        let param = format!("{name}{opt}: {body_ts}");
        if *required {
            required_params.push(param);
        } else {
            optional_params.push(param);
        }
        Some(name)
    } else {
        None
    };

    // Why: TypeScript rejects a required parameter after an optional parameter (TS1016),
    // so emit all required parameters (path, required query, required body) before optional ones.
    let mut sig_params = required_params;
    sig_params.extend(optional_params);

    let _ = writeln!(
        out,
        "\n  async {method_name}({}): Promise<{return_type}> {{",
        sig_params.join(", ")
    );

    let url_expr = build_url_template(path, &path_params);
    if let Some(ref q_param) = query_param_name {
        let _ = writeln!(out, "    const searchParams = new URLSearchParams();");
        for q in &query_params {
            let q_lit = js_string_literal(&q.name);
            let prop_access = if is_valid_js_ident(&q.name) {
                format!("{q_param}?.{}", q.name)
            } else {
                format!("{q_param}?.[{q_lit}]")
            };
            let _ = writeln!(
                out,
                "    if ({prop_access} !== undefined) searchParams.set({q_lit}, String({prop_access}));"
            );
        }
        let _ = writeln!(out, "    const qs = searchParams.toString();");
        let _ = writeln!(
            out,
            "    const url = qs ? `{url_expr}?${{qs}}` : `{url_expr}`;"
        );
    } else {
        let _ = writeln!(out, "    const url = `{url_expr}`;");
    }

    let upper_method = js_string_literal(&method.to_ascii_uppercase());
    if let Some(ref b_param) = body_param_name {
        let _ = writeln!(out, "    const res = await this.fetchImpl(url, {{");
        let _ = writeln!(out, "      method: {upper_method},");
        let _ = writeln!(
            out,
            "      headers: {b_param} !== undefined ? {{ \"Content-Type\": \"application/json\" }} : undefined,"
        );
        let _ = writeln!(
            out,
            "      body: {b_param} !== undefined ? JSON.stringify({b_param}) : undefined,"
        );
        let _ = writeln!(out, "    }});");
    } else {
        let _ = writeln!(
            out,
            "    const res = await this.fetchImpl(url, {{ method: {upper_method} }});"
        );
    }

    out.push_str(
        "    if (!res.ok) {\n      throw new Error(`HTTP ${res.status}: ${await res.text()}`);\n    }\n",
    );
    if return_type == "void" {
        out.push_str("    return;\n");
    } else {
        let _ = writeln!(out, "    return (await res.json()) as {return_type};");
    }
    out.push_str("  }");
}

fn collect_parameters(
    path: &str,
    path_item_params: Option<&[Value]>,
    op: &Map<String, Value>,
    schema_names: &HashMap<&str, String>,
) -> (Vec<ParamSpec>, Vec<ParamSpec>) {
    let mut path_params: Vec<ParamSpec> = Vec::new();
    let mut query_params: Vec<ParamSpec> = Vec::new();
    let mut seen_path = BTreeSet::new();

    // Merge path-item-level `parameters` with operation-level `parameters`, letting
    // operation-level definitions override path-item definitions by `(name, in)` (`RC-39`).
    let mut merged: Vec<&Value> = Vec::new();
    if let Some(pip) = path_item_params {
        merged.extend(pip.iter());
    }
    if let Some(op_params) = op.get("parameters").and_then(Value::as_array) {
        for p in op_params {
            let key = (
                p.get("name").and_then(Value::as_str),
                p.get("in").and_then(Value::as_str),
            );
            if let (Some(name), Some(loc)) = key
                && let Some(pos) = merged.iter().position(|existing| {
                    existing.get("name").and_then(Value::as_str) == Some(name)
                        && existing.get("in").and_then(Value::as_str) == Some(loc)
                })
            {
                merged[pos] = p;
                continue;
            }
            merged.push(p);
        }
    }

    for p in merged {
        let Some(name) = p.get("name").and_then(Value::as_str) else {
            continue;
        };
        let location = p.get("in").and_then(Value::as_str).unwrap_or("");
        let required = p.get("required").and_then(Value::as_bool).unwrap_or(false);
        let ts_type = p
            .get("schema")
            .map(|s| schema_to_ts(s, schema_names))
            .unwrap_or_else(|| "string".to_string());

        match location {
            "path" => {
                seen_path.insert(name.to_string());
                path_params.push(ParamSpec {
                    name: name.to_string(),
                    ts_name: sanitize_param_ident(name),
                    required: true,
                    ts_type,
                });
            }
            "query" => {
                query_params.push(ParamSpec {
                    name: name.to_string(),
                    ts_name: sanitize_param_ident(name),
                    required,
                    ts_type,
                });
            }
            _ => {}
        }
    }

    // Ensure any `{param}` or `{*wildcard}` (including partial-segment `{id}.json`) in the
    // path template is present even if `parameters` omitted it (`RC-39`).
    for (name, _is_wildcard) in extract_path_placeholders(path) {
        if !name.is_empty() && !seen_path.contains(&name) {
            seen_path.insert(name.clone());
            path_params.push(ParamSpec {
                ts_name: sanitize_param_ident(&name),
                name,
                required: true,
                ts_type: "string".to_string(),
            });
        }
    }

    (path_params, query_params)
}

fn extract_path_placeholders(path: &str) -> Vec<(String, bool)> {
    let mut out = Vec::new();
    let mut rest = path;
    while let Some(open) = rest.find('{') {
        // Why: `${...}` in a static path segment is a literal JS template-expression
        // sequence that must be escaped, NOT an OpenAPI `{param}` placeholder.
        if open > 0 && rest.as_bytes()[open - 1] == b'$' {
            rest = &rest[open + 1..];
            continue;
        }
        let after_open = &rest[open + 1..];
        let Some(close) = after_open.find('}') else {
            break;
        };
        let raw = &after_open[..close];
        if let Some(wild) = raw.strip_prefix('*') {
            if !wild.is_empty() {
                out.push((wild.to_string(), true));
            }
        } else if !raw.is_empty() {
            out.push((raw.to_string(), false));
        }
        rest = &after_open[close + 1..];
    }
    out
}

fn extract_request_body(
    op: &Map<String, Value>,
    schema_names: &HashMap<&str, String>,
) -> Option<(bool, String)> {
    let body = op.get("requestBody")?;
    let required = body
        .get("required")
        .and_then(Value::as_bool)
        .unwrap_or(false);
    let schema = body
        .get("content")
        .and_then(|c| c.get("application/json"))
        .and_then(|j| j.get("schema"))?;
    Some((required, schema_to_ts(schema, schema_names)))
}

fn extract_response_type(op: &Map<String, Value>, schema_names: &HashMap<&str, String>) -> String {
    let Some(responses) = op.get("responses").and_then(Value::as_object) else {
        return "void".to_string();
    };

    for status in ["200", "201", "202", "204"] {
        if let Some(resp) = responses.get(status) {
            return response_schema_or_void(status, resp, schema_names);
        }
    }

    if let Some((status, resp)) = responses.iter().find(|(k, _)| k.starts_with('2')) {
        return response_schema_or_void(status, resp, schema_names);
    }

    "void".to_string()
}

fn response_schema_or_void(
    status: &str,
    resp: &Value,
    schema_names: &HashMap<&str, String>,
) -> String {
    if status == "204" {
        return "void".to_string();
    }
    resp.get("content")
        .and_then(|c| c.get("application/json"))
        .and_then(|j| j.get("schema"))
        .map(|s| schema_to_ts(s, schema_names))
        .unwrap_or_else(|| "void".to_string())
}

fn build_url_template(path: &str, path_params: &[ParamSpec]) -> String {
    let mut rendered = String::from("${this.baseUrl}");
    if !path.starts_with('/') {
        rendered.push('/');
    }
    // Why: scan inline `{param}` and `{*wildcard}` occurrences so partial-segment templates
    // like `/files/{id}.json` and wildcard catch-alls like `/assets/{*path}` interpolate
    // properly while `${...}` sequences in static segments stay escaped (`RC-39`).
    let mut rest = path;
    while let Some(open) = rest.find('{') {
        if open > 0 && rest.as_bytes()[open - 1] == b'$' {
            rendered.push_str(&escape_ts_template_literal(&rest[..open - 1]));
            rendered.push_str("\\${");
            rest = &rest[open + 1..];
            continue;
        }
        rendered.push_str(&escape_ts_template_literal(&rest[..open]));
        let after_open = &rest[open + 1..];
        let Some(close) = after_open.find('}') else {
            rendered.push_str(&escape_ts_template_literal(&rest[open..]));
            return rendered;
        };
        let raw = &after_open[..close];
        let (name, is_wildcard) = match raw.strip_prefix('*') {
            Some(wild) => (wild, true),
            None => (raw, false),
        };
        if name.is_empty() {
            rendered.push_str(&escape_ts_template_literal(&rest[open..=open + close + 1]));
        } else {
            let ts_name = path_params
                .iter()
                .find(|p| p.name == name)
                .map(|p| p.ts_name.as_str())
                .unwrap_or(name);
            if is_wildcard {
                let _ = write!(
                    rendered,
                    "${{String({ts_name}).split(\"/\").map(encodeURIComponent).join(\"/\")}}"
                );
            } else {
                let _ = write!(rendered, "${{encodeURIComponent(String({ts_name}))}}");
            }
        }
        rest = &after_open[close + 1..];
    }
    rendered.push_str(&escape_ts_template_literal(rest));
    rendered
}

/// Escape characters that have special meaning inside a JavaScript/TypeScript template literal.
fn escape_ts_template_literal(segment: &str) -> String {
    let mut out = String::with_capacity(segment.len());
    let mut chars = segment.chars().peekable();
    while let Some(ch) = chars.next() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '`' => out.push_str("\\`"),
            '$' if chars.peek() == Some(&'{') => out.push_str("\\$"),
            _ => out.push(ch),
        }
    }
    out
}

fn sanitize_camel_ident(raw: &str) -> String {
    let tokens: Vec<&str> = raw
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|t| !t.is_empty())
        .collect();

    if tokens.is_empty() {
        return "request".to_string();
    }

    let mut out = String::new();
    for (idx, token) in tokens.iter().enumerate() {
        if idx == 0 {
            let mut chars = token.chars();
            if let Some(first) = chars.next() {
                if first.is_ascii_digit() {
                    out.push('_');
                }
                out.push(first.to_ascii_lowercase());
                out.push_str(chars.as_str());
            }
        } else {
            let mut chars = token.chars();
            if let Some(first) = chars.next() {
                out.push(first.to_ascii_uppercase());
                out.push_str(chars.as_str());
            }
        }
    }
    out
}

fn sanitize_pascal_ident(raw: &str) -> String {
    let tokens: Vec<&str> = raw
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|t| !t.is_empty())
        .collect();

    if tokens.is_empty() {
        return "Schema".to_string();
    }

    let mut out = String::new();
    for token in tokens {
        let mut chars = token.chars();
        if let Some(first) = chars.next() {
            if out.is_empty() && first.is_ascii_digit() {
                out.push('_');
            }
            out.push(first.to_ascii_uppercase());
            out.push_str(chars.as_str());
        }
    }
    out
}

fn is_ts_reserved_keyword(ident: &str) -> bool {
    matches!(
        ident,
        "await"
            | "break"
            | "case"
            | "catch"
            | "class"
            | "const"
            | "continue"
            | "debugger"
            | "default"
            | "delete"
            | "do"
            | "else"
            | "enum"
            | "export"
            | "extends"
            | "false"
            | "finally"
            | "for"
            | "function"
            | "if"
            | "implements"
            | "import"
            | "in"
            | "instanceof"
            | "interface"
            | "let"
            | "new"
            | "null"
            | "package"
            | "private"
            | "protected"
            | "public"
            | "return"
            | "static"
            | "super"
            | "switch"
            | "this"
            | "throw"
            | "true"
            | "try"
            | "type"
            | "typeof"
            | "var"
            | "void"
            | "while"
            | "with"
            | "yield"
    )
}

fn sanitize_param_ident(raw: &str) -> String {
    let candidate = if is_valid_js_ident(raw) {
        raw.to_string()
    } else {
        let cleaned: String = raw
            .chars()
            .map(|c| {
                if c.is_ascii_alphanumeric() || c == '_' || c == '$' {
                    c
                } else {
                    '_'
                }
            })
            .collect();
        if cleaned.is_empty() || cleaned.starts_with(|c: char| c.is_ascii_digit()) {
            format!("_{cleaned}")
        } else {
            cleaned
        }
    };
    if is_ts_reserved_keyword(&candidate) {
        format!("{candidate}_")
    } else {
        candidate
    }
}

fn is_valid_js_ident(s: &str) -> bool {
    let mut chars = s.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !(first.is_ascii_alphabetic() || first == '_' || first == '$') {
        return false;
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

fn js_string_literal(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_else(|_| format!("{s:?}"))
}

fn format_prop_key(name: &str) -> String {
    if is_valid_js_ident(name) {
        name.to_string()
    } else {
        js_string_literal(name)
    }
}

fn deduplicate_name(base: String, used: &mut HashSet<String>) -> String {
    if used.insert(base.clone()) {
        return base;
    }
    let mut suffix = 2usize;
    loop {
        let candidate = format!("{base}_{suffix}");
        if used.insert(candidate.clone()) {
            return candidate;
        }
        suffix += 1;
    }
}

