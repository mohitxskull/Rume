    #[test]
    fn generates_interfaces_for_object_schemas_and_required_fields() {
        let spec = json!({
            "openapi": "3.1.0",
            "info": { "title": "Test", "version": "1.0.0" },
            "paths": {},
            "components": {
                "schemas": {
                    "User": {
                        "type": "object",
                        "required": ["id", "email", "active"],
                        "properties": {
                            "id": { "type": "integer", "format": "int64" },
                            "email": { "type": "string" },
                            "nickname": { "type": "string" },
                            "score": { "type": "number" },
                            "active": { "type": "boolean" },
                            "tags": { "type": "array", "items": { "type": "string" } },
                            "meta": {
                                "type": "object",
                                "required": ["source"],
                                "properties": {
                                    "source": { "type": "string" },
                                    "note": { "type": "string" }
                                }
                            }
                        }
                    }
                }
            }
        });

        let ts = generate_typescript(&spec);
        assert!(
            ts.contains("export interface User"),
            "missing User interface:\n{ts}"
        );
        assert!(ts.contains("id: number;"), "missing required id:\n{ts}");
        assert!(
            ts.contains("email: string;"),
            "missing required email:\n{ts}"
        );
        assert!(
            ts.contains("nickname?: string;"),
            "missing optional nickname:\n{ts}"
        );
        assert!(
            ts.contains("score?: number;"),
            "missing optional score:\n{ts}"
        );
        assert!(
            ts.contains("active: boolean;"),
            "missing required active:\n{ts}"
        );
        assert!(
            ts.contains("tags?: Array<string>;") || ts.contains("tags?: string[];"),
            "missing optional tags array:\n{ts}"
        );
        assert!(
            ts.contains("source: string;"),
            "missing nested required source:\n{ts}"
        );
        assert!(
            ts.contains("note?: string;"),
            "missing nested optional note:\n{ts}"
        );
    }

