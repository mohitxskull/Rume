CREATE TABLE IF NOT EXISTS rume_jobs (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    queue VARCHAR(128) NOT NULL DEFAULT 'default',
    priority INT NOT NULL DEFAULT 0,
    payload LONGBLOB NOT NULL,
    attempt INT NOT NULL DEFAULT 0,
    max_attempts INT NOT NULL DEFAULT 3,
    initial_backoff_ms BIGINT NOT NULL DEFAULT 1000,
    max_backoff_ms BIGINT NOT NULL DEFAULT 60000,
    backoff_factor DOUBLE NOT NULL DEFAULT 2.0,
    timeout_ms BIGINT,
    idempotency_key VARCHAR(255),
    tenant_id VARCHAR(255),
    active_tenant_id VARCHAR(255) GENERATED ALWAYS AS (COALESCE(tenant_id, '')) STORED,
    active_idempotency_key VARCHAR(255) GENERATED ALWAYS AS (IF(status NOT IN ('dead_letter', 'purged'), idempotency_key, NULL)) STORED,
    assigned_worker VARCHAR(255),
    available_at BIGINT NOT NULL,
    lease_expires_at BIGINT,
    status VARCHAR(32) NOT NULL DEFAULT 'pending',
    dead_letter_reason TEXT,
    dead_lettered_at BIGINT,
    created_at BIGINT NOT NULL,
    completed_at BIGINT,
    lease_token VARCHAR(64),
    trace_context TEXT,
    INDEX idx_rume_jobs_pending (status, queue, priority, available_at, created_at),
    INDEX idx_rume_jobs_dead_letter (status, dead_lettered_at),
    UNIQUE INDEX idx_rume_jobs_idempotency (active_tenant_id, active_idempotency_key)
) ENGINE=InnoDB;
