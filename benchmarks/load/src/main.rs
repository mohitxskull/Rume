//! Goose load-testing harness for the Rume `workbench/multi-instance` stack.
//!
//! Exercises realistic HTTP + Postgres + Redis + Transactional Outbox workloads:
//! - Health probe (`GET /health`)
//! - 80% reads (`GET /api/v1/organizations`, `GET /api/v1/projects`, `GET /api/v1/projects/{id}/issues`)
//! - 20% writes (`POST /api/v1/projects/{id}/issues` — atomic Postgres insert + transactional outbox)
//!
//! Optional environment variables for authenticated tenant-scoped 80/20 workloads:
//! - `RUME_BENCH_TENANT_ID`: tenant header value (`X-Tenant-Id`)
//! - `RUME_BENCH_BEARER_TOKEN`: bearer token for authenticated tenant routes
//! - `RUME_BENCH_PROJECT_ID`: existing project ID under the tenant for issue read/write tests
//!
//! When those environment variables are not set, the harness runs the public read/health mix
//! (`GET /health`, `GET /api/v1/organizations`) against the target `--host`.

#![forbid(unsafe_code)]

use std::sync::OnceLock;

use goose::goose::GooseResponse;
use goose::prelude::*;
use serde_json::json;

#[derive(Debug, Clone)]
struct BenchAuthConfig {
    tenant_id: String,
    bearer_token: String,
    project_id: String,
}

fn auth_config() -> Option<&'static BenchAuthConfig> {
    static CONFIG: OnceLock<Option<BenchAuthConfig>> = OnceLock::new();
    CONFIG
        .get_or_init(|| {
            let tenant_id = std::env::var("RUME_BENCH_TENANT_ID").ok()?;
            let bearer_token = std::env::var("RUME_BENCH_BEARER_TOKEN").ok()?;
            let project_id = std::env::var("RUME_BENCH_PROJECT_ID").ok()?;
            if tenant_id.is_empty() || bearer_token.is_empty() || project_id.is_empty() {
                return None;
            }
            Some(BenchAuthConfig {
                tenant_id,
                bearer_token,
                project_id,
            })
        })
        .as_ref()
}

async fn ensure_success(
    user: &mut GooseUser,
    mut goose: GooseResponse,
    label: &str,
) -> TransactionResult {
    if let Ok(resp) = goose.response
        && !resp.status().is_success()
    {
        return user.set_failure(
            &format!("{label} returned non-2xx"),
            &mut goose.request,
            None,
            None,
        );
    }
    Ok(())
}

async fn load_health(user: &mut GooseUser) -> TransactionResult {
    let goose = user.get("/health").await?;
    ensure_success(user, goose, "health").await
}

async fn load_list_organizations(user: &mut GooseUser) -> TransactionResult {
    let goose = user.get("/api/v1/organizations").await?;
    ensure_success(user, goose, "list_organizations").await
}

async fn load_list_projects(user: &mut GooseUser) -> TransactionResult {
    let Some(cfg) = auth_config() else {
        return load_list_organizations(user).await;
    };

    let req = user
        .get_request_builder(&GooseMethod::Get, "/api/v1/projects")?
        .header("X-Tenant-Id", &cfg.tenant_id)
        .bearer_auth(&cfg.bearer_token);
    let goose_req = GooseRequest::builder().set_request_builder(req).build();
    let goose = user.request(goose_req).await?;
    ensure_success(user, goose, "list_projects").await
}

async fn load_list_issues(user: &mut GooseUser) -> TransactionResult {
    let Some(cfg) = auth_config() else {
        return load_list_organizations(user).await;
    };

    let path = format!("/api/v1/projects/{}/issues", cfg.project_id);
    let req = user
        .get_request_builder(&GooseMethod::Get, &path)?
        .header("X-Tenant-Id", &cfg.tenant_id)
        .bearer_auth(&cfg.bearer_token);
    let goose_req = GooseRequest::builder().set_request_builder(req).build();
    let goose = user.request(goose_req).await?;
    ensure_success(user, goose, "list_issues").await
}

async fn load_create_issue_with_outbox(user: &mut GooseUser) -> TransactionResult {
    let Some(cfg) = auth_config() else {
        return load_health(user).await;
    };

    let path = format!("/api/v1/projects/{}/issues", cfg.project_id);
    let body = json!({
        "title": format!("Load test issue {}", uuid::Uuid::new_v4()),
        "description": "Generated by Goose 80/20 load harness",
        "status": "open",
        "priority": "medium"
    });
    let req = user
        .get_request_builder(&GooseMethod::Post, &path)?
        .header("X-Tenant-Id", &cfg.tenant_id)
        .bearer_auth(&cfg.bearer_token)
        .json(&body);
    let goose_req = GooseRequest::builder().set_request_builder(req).build();
    let goose = user.request(goose_req).await?;
    ensure_success(user, goose, "create_issue").await
}

#[tokio::main]
async fn main() -> Result<(), GooseError> {
    GooseAttack::initialize()?
        // 80/20 weighted read/write scenario:
        // - 10% health probes
        // - 35% list projects
        // - 35% list issues
        // - 20% create issue (atomic Postgres transaction + transactional outbox enqueue)
        .register_scenario(
            scenario!("Workbench8020Mix")
                .register_transaction(transaction!(load_health).set_weight(2)?)
                .register_transaction(transaction!(load_list_projects).set_weight(7)?)
                .register_transaction(transaction!(load_list_issues).set_weight(7)?)
                .register_transaction(transaction!(load_create_issue_with_outbox).set_weight(4)?),
        )
        .execute()
        .await?;

    Ok(())
}
